-- Monitoring ingest storage for client-side failure events.
-- Rollback: drop table public.monitoring_events.

create table if not exists public.monitoring_events (
  id bigint generated by default as identity primary key,
  kind text not null default 'failure',
  domain text not null check (domain in ('auth', 'rpc', 'realtime', 'storage')),
  operation text not null,
  message text not null,
  details jsonb not null default '{}'::jsonb,
  count_in_window integer not null default 1 check (count_in_window >= 0),
  threshold integer not null default 0 check (threshold >= 0),
  window_ms integer not null default 0 check (window_ms >= 0),
  app_version text,
  source text not null default 'web',
  created_at timestamptz not null default now()
);

create index if not exists monitoring_events_created_at_idx
  on public.monitoring_events (created_at desc);

create index if not exists monitoring_events_domain_created_at_idx
  on public.monitoring_events (domain, created_at desc);

create index if not exists monitoring_events_operation_created_at_idx
  on public.monitoring_events (operation, created_at desc);

alter table public.monitoring_events enable row level security;

-- No client access by default; ingest and reads should happen through trusted services/admin RPCs.
